import { chromium } from 'playwright';
import { createServer } from 'node:http';
import { readFileSync, existsSync } from 'node:fs';
import { join, extname } from 'node:path';
const HERE = new URL('.', import.meta.url).pathname;
const T = { '.js': 'text/javascript', '.mjs': 'text/javascript', '.css': 'text/css', '.html': 'text/html', '.json': 'application/json' };
const server = createServer((req, res) => { const url = req.url.split('?')[0]; const f = url.startsWith('/assets/') ? join(HERE, url) : join(HERE, 'dist', url);
  if (!existsSync(f)) return res.writeHead(404).end(); res.writeHead(200, { 'content-type': T[extname(f)] ?? 'application/octet-stream' }).end(readFileSync(f)); }).listen(0);
const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const p = await b.newPage();
p.on('pageerror', (e) => console.log('ERR', e.stack.slice(0,900))); p.on('console', (m) => console.log(m.type(), m.text().slice(0, 300)));
await p.goto(`http://127.0.0.1:${server.address().port}/${process.argv[2]}`);
await p.waitForTimeout(8000);
await b.close(); server.close();
